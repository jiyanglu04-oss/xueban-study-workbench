# -*- coding: utf-8 -*-
"""判断一条通知「要不要我做点什么」，用于把通知自动转成待办。

规则不是拍脑袋写的：是对着真实抓到的 37 条学习通 / 雨课堂通知一条条过出来的。
设计上分两步 —— **先判「纯信息」再判「要做事」**：

    要做的（命中就变待办）：
        作业:《高等数学2（经4）》C9—测验题     -> 作业
        考试通知 / C8-9阶段考试                 -> 考试
        2026年大学生数学竞赛报名通知            -> 报名
        《创业基础》课程安排及课程群（必读）     -> 加群
        今天大家应该收到了学委安排的扫码填问卷   -> 问卷

    不要做的（看一眼就够了，变成待办只会污染列表）：
        课堂互动情况 / 活动结束提醒 / 课件已上传 /
        《金融学》教材 / 考试成绩 / 辛苦大家尽量到课

为什么要有「不要做」这一层：通知里「考试」两个字出现得太频繁了
（「考试座位表」「考试注意事项」「期末考试基本要求」），
只靠正向关键词会把它们全变成待办，反而看不见真正要交的作业。
"""
from __future__ import annotations

import re

# (分类, 建议优先级, 正则)。优先级 1 高 / 2 中 / 3 低，跟工作台 UI 一致。
ACTION_RULES: tuple[tuple[str, int, re.Pattern], ...] = (
    ("exam", 1, re.compile(
        r"考试|考查|期中|期末|补考|随堂测|阶段考|测评|答辩|开卷|闭卷")),
    ("homework", 1, re.compile(
        r"作业|习题|测验|测试|实验|实训|报告|论文|实践作业|大作业|课程设计")),
    ("signup", 2, re.compile(
        r"报名|申请|选课|退课|缴费|登记|填报|确认信息|提交材料|资格审查")),
    ("social", 3, re.compile(
        r"加入.{0,6}(群|微助教|微信|QQ)|加群|进群|扫码|二维码|问卷|组队|分组|"
        r"课程群|班级群|学习群|钉钉|课程群二维码")),
)

# 纯信息类通知：命中就当作「不需要行动」。
# 「到课」放在这里是有意的 —— 「辛苦大家务必到课」是提醒，不是待办。
IGNORE_RE = re.compile(
    r"课堂互动情况|活动结束提醒|课件已上传|答案已开放|教材|到课|上课提醒|"
    r"座位表|考试成绩|成绩公布|已结束|补考名单")

# 分类 -> 工作台消息列表上的角标类型
KIND_OF = {"homework": "homework", "exam": "exam"}

# 自动转待办时，只认最近这么多天发出的通知。
# 不加这个窗口的话，第一次同步会把 4~7 月的历史通知一次性倒进待办，
# 几十条早就做完的事堆在一起，真正要做的反而看不见。
LOOKBACK_DAYS = 21

_LABEL = {
    "homework": "作业或习题",
    "exam": "考试或测验",
    "signup": "报名 / 申请类事项",
    "social": "加群或扫码类事项",
}


def classify_action(text: str) -> tuple[str, int] | None:
    """返回 (分类, 优先级)；判断不出需要行动时返回 None。"""
    t = str(text or "")
    if not t or IGNORE_RE.search(t):
        return None
    for kind, priority, rx in ACTION_RULES:
        if rx.search(t):
            return kind, priority
    return None


def action_label(kind: str) -> str:
    return _LABEL.get(kind, "待办事项")
