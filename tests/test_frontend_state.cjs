const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readdirSync('src/js').filter(f => f.endsWith('.js')).sort().map(f => fs.readFileSync('src/js/' + f, 'utf8')).join('\n');
const exposed = source.replace(/\}\)\(\);\s*\/\* 收尾说明[\s\S]*$/, 'globalThis.apiForTest={defaultState,applyState,termMonday,validSessionWeeks,parseWeeks,inWeek,weeksFromRule,finalExamStatus,getState:()=>S};})();');
const context = {document: {readyState:'loading', addEventListener(){}}, location:{protocol:'file:'}, window:{}, console};
vm.createContext(context); vm.runInContext(exposed, context);
const api = context.apiForTest;
assert.ok(api, 'test export injected before IIFE close');
assert.equal(api.termMonday('2026-09-09'), '2026-09-07');
assert.equal(api.termMonday('2026-02-30'), '');
assert.equal(api.validSessionWeeks('2-16双',20),true);
assert.equal(api.validSessionWeeks('16-2双',20),false);
assert.equal(api.validSessionWeeks('1-25',20),false);
assert.equal(api.validSessionWeeks('2-2单',20),false);
assert.equal(api.validSessionWeeks('1-8,10-16',20),true);
assert.equal(api.inWeek('1-16单',3),true);
assert.equal(api.inWeek('1-16单',4),false);
assert.equal(api.inWeek('2-16双',4),true);
const values = {'.s-parity':'双','.s-from':'3','.s-to':'15','.s-weeks':'1-16单'};
const root = {querySelector: selector => ({value:values[selector]})};
assert.equal(api.weeksFromRule(root),'3-15双', 'read latest controls even before blur');
values['.s-parity']='custom'; values['.s-weeks']='1-8,10-16';
assert.equal(api.weeksFromRule(root),'1-8,10-16');
assert.equal(api.finalExamStatus('2026-10-13',new Date('2026-10-12T12:00:00')).days,1);
assert.equal(api.finalExamStatus('2026-10-12',new Date('2026-10-12T12:00:00')).text,'今天考试');
assert.equal(api.finalExamStatus('2026-10-11',new Date('2026-10-12T12:00:00')).text,'已结束 1 天');
api.applyState({cet:{type:'CET-4'},settings:{termStart:'2026-09-07'}});
assert.equal(api.getState().cet.finalExams.length,0);
api.applyState({cet:{finalExams:[{id:'f1',title:'期末',date:'2027-01-12'}]}});
assert.equal(api.getState().cet.finalExams[0].date,'2027-01-12');
console.log('Frontend date, parity, validation and legacy-state tests: OK');
